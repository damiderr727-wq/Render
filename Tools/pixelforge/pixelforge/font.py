def _rows(char: str) -> tuple[str, ...]:
    for table in (_UPPER, _DIGITS, _PUNCT):
        if char in table:
            return table[char]
    if char in _LOWER:
        return _LOWER[char]
    return _PUNCT[" "]


CHARSET = "".join(sorted(set(
    list(_UPPER) + list(_LOWER) + list(_DIGITS) + list(_PUNCT))))


def glyph(char: str, color: RGBA = (255, 255, 255, 255)) -> Canvas:
    """Render one character into a GLYPH_W x GLYPH_H canvas."""
    c = Canvas(GLYPH_W, GLYPH_H)
    for y, row in enumerate(_rows(char)):
        if y >= GLYPH_H:
            break
        for x, bit in enumerate(row[:GLYPH_W]):
            if bit == "#":
                c.set(x, y, color)
    return c


def ink_width(char: str) -> int:
    """Width of the glyph's actual ink, so text can be proportionally spaced.
    Space keeps a fixed 3px width because it has no ink to measure."""
    if char == " ":
        return 3
    widest = 0
    for row in _rows(char):
        stripped = row.rstrip(".")
        widest = max(widest, len(stripped))
    return max(1, widest)


def text_width(s: str, tracking: int = 1) -> int:
    if not s:
        return 0
    return sum(ink_width(ch) + tracking for ch in s) - tracking


def render_text(s: str, color: RGBA = (255, 255, 255, 255),
                tracking: int = 1, shadow: RGBA | None = None) -> Canvas:
    """Draw a whole string. ``shadow`` offsets a second pass down-right, which
    is what keeps white text readable over a bright explosion."""
    w = text_width(s, tracking)
    c = Canvas(max(1, w + (1 if shadow else 0)), GLYPH_H + (1 if shadow else 0))
    x = 0
    for ch in s:
        g = glyph(ch, color)
        if shadow:
            c.blit(glyph(ch, shadow), x + 1, 1)
        c.blit(g, x, 0)
        x += ink_width(ch) + tracking
    return c


def build_font_sheet(color: RGBA = (238, 240, 250, 255)) -> dict[str, Canvas]:
    """One canvas per glyph, ready for the atlas packer."""
    return {ch: glyph(ch, color) for ch in CHARSET}
